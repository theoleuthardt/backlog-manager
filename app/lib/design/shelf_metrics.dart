/// Corner radii of the design; only chips are pills.
abstract final class ShelfRadius {
  static const control = 8.0;
  static const card = 12.0;
  static const panel = 14.0;
  static const dialog = 16.0;
  static const window = 12.0;
}

/// Heights of controls.
abstract final class ShelfHeight {
  static const control = 32.0;
  static const input = 34.0;
}
