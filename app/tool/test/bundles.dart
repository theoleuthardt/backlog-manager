/// Writes the test bundles and prints the files `flutter test` should run.
///
/// A bundle is one test file that calls the `main` of many other test files,
/// each in a group of its own. `flutter test` starts a process per file, and
/// the first widget test of every process pays about a second and a half of
/// warm-up (cold code, first layouts); a bundle pays it once for all the files
/// in it. The tests themselves stay where they are: the golden tests keep
/// running from their own files (their image paths belong to the file), and a
/// file that changes the whole process (it loads the real font) or has an
/// asynchronous `main` is run on its own.
///
/// Usage: `dart run tool/test/bundles.dart <count>` prints the bundle files,
/// then the files that run on their own, one path per line.
library;

import 'dart:io';

const _bundleDirectory = 'test/bundles';

class _TestFile {
  _TestFile(this.path, String source)
    : weight =
          RegExp(r'testWidgets\(').allMatches(source).length * 5 +
          RegExp(r'\btest\(').allMatches(source).length,
      standalone =
          source.contains('loadAppFont') ||
          RegExp(r'Future<void>\s+main|main\([^)]*\)\s+async').hasMatch(source);

  final String path;
  final int weight;
  final bool standalone;

  String get name =>
      path.replaceFirst('test/', '').replaceFirst(RegExp(r'_test\.dart$'), '');

  String get alias => name.replaceAll(RegExp(r'[^A-Za-z0-9]'), '_');
}

void main(List<String> args) {
  final count = int.parse(args.first);
  final files = [
    for (final entity in Directory('test').listSync(recursive: true))
      if (entity is File &&
          entity.path.endsWith('_test.dart') &&
          !entity.path.startsWith('$_bundleDirectory/'))
        _TestFile(entity.path, entity.readAsStringSync()),
  ]..sort((a, b) => a.path.compareTo(b.path));

  final bundled = [
    for (final f in files)
      if (!f.standalone) f,
  ];
  final alone = [
    for (final f in files)
      if (f.standalone) f,
  ];

  final loads = List<int>.filled(count, 0);
  final bundles = List.generate(count, (_) => <_TestFile>[]);
  final heaviestFirst = [...bundled]
    ..sort((a, b) => b.weight.compareTo(a.weight));
  for (final file in heaviestFirst) {
    var lightest = 0;
    for (var i = 1; i < count; i++) {
      if (loads[i] < loads[lightest]) lightest = i;
    }
    bundles[lightest].add(file);
    loads[lightest] += file.weight;
  }

  final directory = Directory(_bundleDirectory);
  if (directory.existsSync()) directory.deleteSync(recursive: true);
  directory.createSync(recursive: true);

  final written = <String>[];
  for (var i = 0; i < count; i++) {
    final members = bundles[i]..sort((a, b) => a.path.compareTo(b.path));
    if (members.isEmpty) continue;
    final out = StringBuffer()
      ..writeln('/// Generated by tool/test/bundles.dart, not committed.')
      ..writeln("import 'package:flutter_test/flutter_test.dart';")
      ..writeln();
    for (final file in members) {
      out.writeln(
        "import '../${file.path.replaceFirst('test/', '')}' as ${file.alias};",
      );
    }
    out
      ..writeln()
      ..writeln('void main() {');
    for (final file in members) {
      out.writeln("  group('${file.name}', ${file.alias}.main);");
    }
    out.writeln('}');
    final path = '$_bundleDirectory/bundle_$i.dart';
    File(path).writeAsStringSync(out.toString());
    written.add(path);
  }

  for (final path in [...written, ...alone.map((f) => f.path)]) {
    stdout.writeln(path);
  }
}
